        action = (
            deepcopy(ROUTINE_ACTIONS[step])
            if 0 <= step < len(ROUTINE_ACTIONS)
            else deepcopy(SAFE_PASS)
        )
        if step == 195:
            for order in action.get("market", []) or []:
                if order[:2] == ["BUY_PRODUCT", "WHEAT"]:
                    order[2] = max(4, int(order[2]))
                    break
            action["market"] = [
                order
                for order in action.get("market", []) or []
                if order[:2] != ["BUY_ANIMAL", "COW"]
            ]
        return action


